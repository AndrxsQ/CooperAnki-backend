CREATE SCHEMA IF NOT EXISTS coopera;

CREATE TABLE coopera.organizations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    type VARCHAR(30),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE coopera.roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL,
    description TEXT,
    CONSTRAINT uq_roles_name UNIQUE (name)
);

CREATE TABLE coopera.permissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(100) NOT NULL,
    CONSTRAINT uq_permissions_code UNIQUE (code)
);

CREATE TABLE coopera.role_permissions (
    role_id BIGINT NOT NULL,
    permission_id BIGINT NOT NULL,
    CONSTRAINT pk_role_permissions PRIMARY KEY (role_id, permission_id),
    CONSTRAINT fk_role_permissions_role
        FOREIGN KEY (role_id) REFERENCES coopera.roles (id) ON DELETE CASCADE,
    CONSTRAINT fk_role_permissions_permission
        FOREIGN KEY (permission_id) REFERENCES coopera.permissions (id) ON DELETE CASCADE
);

CREATE TABLE coopera.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT,
    role_id BIGINT NOT NULL,
    full_name VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT fk_users_organization
        FOREIGN KEY (organization_id) REFERENCES coopera.organizations (id),
    CONSTRAINT fk_users_role
        FOREIGN KEY (role_id) REFERENCES coopera.roles (id)
);

CREATE INDEX idx_role_permissions_permission_id ON coopera.role_permissions (permission_id);
CREATE INDEX idx_users_organization_id ON coopera.users (organization_id);
CREATE INDEX idx_users_role_id ON coopera.users (role_id);
