CREATE TABLE public.funding_opportunities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_url TEXT NOT NULL,
    title VARCHAR(255) NOT NULL,
    cooperating_entity VARCHAR(150),
    requirements_description TEXT,
    max_amount NUMERIC(15, 2),
    closing_date DATE,
    embedding_vector vector(1536),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_funding_opportunities_max_amount
        CHECK (max_amount IS NULL OR max_amount > 0),
    CONSTRAINT ck_funding_opportunities_source_url
        CHECK (source_url ~* '^https?://')
);

CREATE TABLE public.project_matches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    funding_opportunity_id BIGINT NOT NULL,
    compatibility_score NUMERIC(5, 2) NOT NULL,
    nlp_justification JSONB,
    match_status VARCHAR(20) NOT NULL DEFAULT 'SUGGESTED',
    calculated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_project_matches_project_opportunity
        UNIQUE (project_id, funding_opportunity_id),
    CONSTRAINT ck_project_matches_score
        CHECK (compatibility_score >= 0 AND compatibility_score <= 100),
    CONSTRAINT ck_project_matches_status
        CHECK (match_status IN ('SUGGESTED', 'APPLIED', 'REJECTED')),
    CONSTRAINT fk_project_matches_project
        FOREIGN KEY (project_id) REFERENCES public.projects (id) ON DELETE CASCADE,
    CONSTRAINT fk_project_matches_opportunity
        FOREIGN KEY (funding_opportunity_id) REFERENCES public.funding_opportunities (id) ON DELETE CASCADE
);

CREATE INDEX idx_project_matches_score
    ON public.project_matches (compatibility_score DESC, calculated_at DESC);
CREATE INDEX idx_project_matches_opportunity_id
    ON public.project_matches (funding_opportunity_id);
