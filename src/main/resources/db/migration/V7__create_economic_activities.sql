CREATE TABLE economic_activities (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ciiu_id VARCHAR(4) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL
);

CREATE TABLE unit_activities (
    unit_id VARCHAR(20) NOT NULL,
    activity_id VARCHAR(4) NOT NULL,
    CONSTRAINT pk_unit_activities PRIMARY KEY (unit_id, activity_id),
    CONSTRAINT fk_unit_activities_activity
        FOREIGN KEY (activity_id) REFERENCES economic_activities (ciiu_id)
);

CREATE UNIQUE INDEX uq_economic_units_doc_number
    ON economic_units (doc_number);

