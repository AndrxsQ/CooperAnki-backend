CREATE TABLE survey_responses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE survey_questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    response_id BIGINT NOT NULL,
    parent_question_id BIGINT,
    question_code VARCHAR(120) NOT NULL,
    section VARCHAR(255) NOT NULL,
    prompt TEXT NOT NULL,
    question_type VARCHAR(40) NOT NULL,
    display_order INTEGER NOT NULL,
    options JSONB,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT fk_survey_questions_response
        FOREIGN KEY (response_id) REFERENCES survey_responses (id) ON DELETE CASCADE,
    CONSTRAINT fk_survey_questions_parent
        FOREIGN KEY (parent_question_id) REFERENCES survey_questions (id) ON DELETE CASCADE,
    CONSTRAINT uq_survey_questions_response_code UNIQUE (response_id, question_code)
);

CREATE TABLE survey_answers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id BIGINT NOT NULL UNIQUE,
    answer JSONB NOT NULL,
    CONSTRAINT fk_survey_answers_question
        FOREIGN KEY (question_id) REFERENCES survey_questions (id) ON DELETE CASCADE
);

CREATE INDEX idx_survey_questions_response_order
    ON survey_questions (response_id, display_order, id);

CREATE INDEX idx_survey_questions_code
    ON survey_questions (question_code);

CREATE INDEX idx_survey_questions_parent_id
    ON survey_questions (parent_question_id);
