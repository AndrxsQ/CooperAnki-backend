CREATE TABLE coopera.refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash VARCHAR(64) NOT NULL,
    subject VARCHAR(255) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    revoked_at TIMESTAMPTZ,
    CONSTRAINT uq_refresh_tokens_token_hash UNIQUE (token_hash)
);

CREATE INDEX idx_refresh_tokens_subject ON coopera.refresh_tokens (subject);
CREATE INDEX idx_refresh_tokens_expires_at ON coopera.refresh_tokens (expires_at);

INSERT INTO coopera.roles (name, description) VALUES
    ('ADMIN', 'Administrator with access to all platform systems'),
    ('TERRITORIAL_TRAINER', 'Territorial trainer for Coopera2075'),
    ('COOPERANT', 'Cooperation partner for Coopera2075')
ON CONFLICT (name) DO NOTHING;

INSERT INTO coopera.permissions (code) VALUES
    ('SYSTEM_COOPERA_ACCESS'),
    ('SYSTEM_ECONOMIC_UNITS_ACCESS')
ON CONFLICT (code) DO NOTHING;

INSERT INTO coopera.role_permissions (role_id, permission_id)
SELECT role.id, permission.id
FROM coopera.roles role
CROSS JOIN coopera.permissions permission
WHERE (role.name = 'ADMIN'
        AND permission.code IN ('SYSTEM_COOPERA_ACCESS', 'SYSTEM_ECONOMIC_UNITS_ACCESS'))
   OR (role.name IN ('TERRITORIAL_TRAINER', 'COOPERANT')
        AND permission.code = 'SYSTEM_COOPERA_ACCESS')
ON CONFLICT (role_id, permission_id) DO NOTHING;
