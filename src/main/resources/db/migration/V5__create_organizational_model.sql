CREATE TABLE departments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255)
);

CREATE TABLE municipalities (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    department_id INTEGER NOT NULL,
    CONSTRAINT fk_municipalities_department
        FOREIGN KEY (department_id) REFERENCES departments (id)
);

CREATE TABLE organizations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    department_id INTEGER NOT NULL,
    municipality_id INTEGER NOT NULL,
    CONSTRAINT fk_organizations_department
        FOREIGN KEY (department_id) REFERENCES departments (id),
    CONSTRAINT fk_organizations_municipality
        FOREIGN KEY (municipality_id) REFERENCES municipalities (id)
);

CREATE TABLE economic_units (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doc_number VARCHAR(255),
    name VARCHAR(255),
    age INTEGER,
    department_id INTEGER NOT NULL,
    municipality_id INTEGER NOT NULL,
    node_id INTEGER NOT NULL,
    economic_activity VARCHAR(255),
    address VARCHAR(255),
    tel_number INTEGER,
    email VARCHAR(255),
    asociation_id INTEGER,
    CONSTRAINT fk_economic_units_department
        FOREIGN KEY (department_id) REFERENCES departments (id),
    CONSTRAINT fk_economic_units_municipality
        FOREIGN KEY (municipality_id) REFERENCES municipalities (id),
    CONSTRAINT fk_economic_units_organization
        FOREIGN KEY (asociation_id) REFERENCES organizations (id)
);

CREATE TABLE nodes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    org_id INTEGER NOT NULL,
    department_id INTEGER NOT NULL,
    municipality_id INTEGER NOT NULL,
    CONSTRAINT fk_nodes_organization
        FOREIGN KEY (org_id) REFERENCES organizations (id),
    CONSTRAINT fk_nodes_department
        FOREIGN KEY (department_id) REFERENCES departments (id),
    CONSTRAINT fk_nodes_municipality
        FOREIGN KEY (municipality_id) REFERENCES municipalities (id)
);

ALTER TABLE economic_units
    ADD CONSTRAINT fk_economic_units_node
    FOREIGN KEY (node_id) REFERENCES nodes (id);

CREATE TABLE org_executives (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    doc_number VARCHAR(255),
    role VARCHAR(255),
    org_id INTEGER,
    CONSTRAINT fk_org_executives_organization
        FOREIGN KEY (org_id) REFERENCES organizations (id)
);

CREATE INDEX idx_municipalities_department_id ON municipalities (department_id);
CREATE INDEX idx_organizations_department_id ON organizations (department_id);
CREATE INDEX idx_organizations_municipality_id ON organizations (municipality_id);
CREATE INDEX idx_economic_units_department_id ON economic_units (department_id);
CREATE INDEX idx_economic_units_municipality_id ON economic_units (municipality_id);
CREATE INDEX idx_economic_units_asociation_id ON economic_units (asociation_id);
CREATE INDEX idx_economic_units_node_id ON economic_units (node_id);
CREATE INDEX idx_nodes_org_id ON nodes (org_id);
CREATE INDEX idx_nodes_department_id ON nodes (department_id);
CREATE INDEX idx_nodes_municipality_id ON nodes (municipality_id);
CREATE INDEX idx_org_executives_org_id ON org_executives (org_id);
