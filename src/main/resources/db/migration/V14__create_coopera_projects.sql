CREATE TABLE coopera.projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    creator_id BIGINT NOT NULL,
    identifier_code VARCHAR(50) NOT NULL,
    title VARCHAR(255) NOT NULL,
    executive_summary TEXT,
    requested_budget NUMERIC(15, 2),
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    embedding_vector vector(1536),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_projects_identifier_code UNIQUE (identifier_code),
    CONSTRAINT ck_projects_status
        CHECK (status IN ('DRAFT', 'IN_REVIEW', 'PUBLISHED', 'FUNDED')),
    CONSTRAINT ck_projects_requested_budget
        CHECK (requested_budget IS NULL OR requested_budget > 0),
    CONSTRAINT fk_projects_organization
        FOREIGN KEY (organization_id) REFERENCES coopera.organizations (id),
    CONSTRAINT fk_projects_creator
        FOREIGN KEY (creator_id) REFERENCES coopera.users (id)
);

CREATE INDEX idx_projects_organization_id ON coopera.projects (organization_id);
CREATE INDEX idx_projects_creator_id ON coopera.projects (creator_id);
CREATE INDEX idx_projects_status ON coopera.projects (status);

CREATE TABLE coopera.project_attachments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    file_name VARCHAR(255) NOT NULL,
    s3_url TEXT NOT NULL,
    mime_type VARCHAR(50),
    size_bytes BIGINT,
    CONSTRAINT ck_project_attachments_size_bytes
        CHECK (size_bytes IS NULL OR size_bytes > 0),
    CONSTRAINT fk_project_attachments_project
        FOREIGN KEY (project_id) REFERENCES coopera.projects (id) ON DELETE CASCADE
);

CREATE INDEX idx_project_attachments_project_id
    ON coopera.project_attachments (project_id);
